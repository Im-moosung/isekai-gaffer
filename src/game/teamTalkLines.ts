/** 상황·톤에 맞는 문장을 경기 시드로 결정론적으로 선택한다(변형 A/B는 seed 홀짝).
 *  같은 (tone, situation, seed)면 항상 같은 문장 → 재현성. */
export function getLine(tone: TeamTalkTone, situation: ScoreSituation, seed: number): string {
  const [a, b] = TEAM_TALK_LINES[tone][situation]
  // seed는 음수일 수 있으므로 안전하게 0/1로 정규화한다.
  return ((seed % 2) + 2) % 2 === 0 ? a : b
}
