// src/ui/landing/camera.ts
// 랜딩 3D 배경 카메라 궤적 — three·React에 의존하지 않는 순수 모듈.
// StadiumBackdrop(렌더러)과 톤 계측 하네스, 회귀 테스트가 같은 정의를 공유한다.
// 왜 360° 풀 오빗을 버렸는가:
//   scene.ts의 조명탑 4기는 px = ±(59.5 + 26*0.85) = ±81.6, pz = ±(41 + 26*0.85) = ±63.1에
//   서 있다 → 원점 기준 방위각 ±37.7°·±142.3°(=atan2(63.1, 81.6) = 0.658rad), 원점 거리 103m.
//   반경 148m 풀 오빗은 한 바퀴에 이 4기를 전부 통과하고, 그때마다 마스트와 y=43의 발광
//   리그가 화면을 가로지르며 프레임의 1/6을 흰 덩어리로 태웠다(계측 스크린샷으로 확인).
//
// 새 구도: **골대 뒤 호(arc) 왕복**.
//   마스트 방위각 사이의 가장 넓은 빈 구간이 142.3°~217.7°(폭 75.4°)이고 그 중심이
//   골대 뒤 180°다. 여기서는 가까운 마스트 2기가 시야축에서 45° 이상 벗어나 절대 프레임에
//   들어오지 않고, 반대편 조명탑 2기는 200m 밖 프레임 상단에 halo로 남는다 —
//   "조명탑이 보이되 가리지는 않는" 유일한 각도다.
//
// [2026-08-01 타이틀 리디자인] 그 호의 중심을 189.1°에서 **정확히 180°**로 옮기고
//   시선 높이를 16m → 22m로 올렸다. 근거는 사용자가 만든 타이틀 시안
//   (docs/refs/title/game-intro-title-v2.png)이다 — 시안은 카메라를 골대 뒤 정면에
//   대칭으로 세우고, 소실점 **위쪽**(원경 스탠드~밤하늘)의 빈 띠에 타이틀을 올린다.
//   · 180°: 좌우 스탠드가 대칭 쐐기로 프레임을 만들고 소실점이 화면 정중앙에 박힌다.
//     "3/4 원근이 도면보다 낫다"는 예전 판단은 문안이 좌하단일 때의 이야기였다.
//     중앙 정렬 타이틀 아래에서는 비대칭이 곧 "기울어진 사진"으로 읽힌다.
//   · 22m: 카메라를 위로 틀면 피치가 화면 아래로 내려가고 상단에 어두운 띠가 생긴다.
//     그 띠가 제목 자리다(실측: 잔디 상단 경계가 화면 44%→53%로 내려갔다).
//
// [2026-08-01 명암 배분] 위 변경은 방향이 맞았지만 **거리**를 안 건드렸다. 그래서 잔디가
//   여전히 하단 절반을 밝은 초록으로 채우고, 좌우 관중석이 빨강·파랑 V자로 시선을 뺏었다
//   (docs/audit/shots/title-1600x900.png ↔ 시안). 반경을 110 → **126m**로 물리고 시선을
//   22 → **23.5m**로 조금 더 올린다.
//   · 126m: 같은 화각에서 피치의 화면 점유가 거리의 제곱만큼 줄고, 좌우 근경 스탠드가
//     60m→90m 뒤로 밀려 포그(backdrop-tone.ts가 84~300m로 당긴다)에 잠긴다. 즉 관중을
//     **지우지 않고 멀리 보내서** 조용하게 만든다. 잔디 상단 경계는 53% → 60%로 내려간다.
//   · 왜 반경 상한이 있는가: 뒤로 물릴수록 가까운 마스트 2기의 시야축 이탈각이 준다.
//     110m에서 65.8°, 126m에서 54.9°, 150m에서 42.7°인데 21:9(2.33)의 수평 반화각이
//     38.8°이고 여기서 호 진폭 4°를 더 빼야 한다 → 150m는 여유가 1°도 안 남는다.
//     126m는 11° 여유를 남긴다. 회귀 테스트가 종횡비 2.4로 프러스텀 검증을 계속한다.
//   · 23.5m: 60%의 마지막 한 걸음. 더 올리면 골대 뒤 근경 스탠드의 검은 지붕이
//     프레임 하단을 먹고, 조명탑 halo가 제목 1행 위로 더 내려온다(실측 대비가 떨어진다).

/**
 * 오빗 기준 반경(m) — 골대 뒤 상단 관중석 눈높이. 가까운 조명탑이 프레임 밖으로 밀려나는 거리다.
 * [2026-08-01] 110 → 126. 근거는 파일 헤더의 "명암 배분" 절.
 */
const ORBIT_R = 126
/** 카메라 높이(m) — 어퍼티어 눈높이. 잔디 mowing 줄무늬가 깔리고 반대편 스탠드가 다 보인다. */
const ORBIT_Y = 50
/**
 * 호의 중심 방위각(rad). 정확히 180° — 마스트 없는 구간(142.3°~217.7°)의 한복판이자
 * 골대 뒤 정면이다. 중앙 정렬 타이틀의 축과 소실점이 같은 세로선 위에 놓인다.
 */
const ARC_CENTER = Math.PI
/**
 * 왕복 진폭(rad ≈ 4°) — 호 범위는 176°~184°. [2026-08-01] 9.2°에서 줄였다:
 * 대칭 구도의 값어치는 "정면"에 있는데 ±9.2°는 30초만 지나도 눈에 띄게 기울어
 * 타이틀 축과 소실점이 어긋난다. ±4°는 살아 있다는 신호는 남기되 대칭은 지킨다.
 * 21:9 울트라와이드에서도 가까운 조명탑은 프레임 밖에 남는다(회귀 테스트가 프러스텀으로 검증).
 */
const ARC_AMP = 0.07
/**
 * 왕복 각속도(rad/s) — 주기 약 121초. sin 왕복이라 끝점에서 속도가 0으로 수렴해
 * 급정거가 없고, 최대 각속도는 0.0083rad/s로 예전 풀 오빗(0.03)의 1/3.6이다(멀미 방지).
 */
const ARC_OMEGA = 0.052
/** 전후 달리(m)와 각속도 — 호와 다른 주기(약 170초)로 어긋나 궤적이 반복처럼 보이지 않는다. */
const DOLLY_AMP = 4
const DOLLY_OMEGA = 0.037
/** 상하 드리프트 진폭(m)과 각속도 — 손으로 든 카메라 느낌의 미세 호흡. */
const BOB_AMP = 1.2
const BOB_OMEGA = 0.11
/** 시야각. */
export const FOV = 38
/**
 * 시선 목표 높이(m). 피치 센터(6)가 아니라 스탠드 상단 높이를 본다 — 카메라를 위로 틀면
 * 반대편 조명탑 2기가 프레임 상단에 halo와 함께 들어오고(3D의 증거), 동시에 가까운
 * 조명탑은 시야축에서 더 멀어져 화면 밖으로 밀린다. 두 요구를 동시에 만족시키는 축이다.
 * [2026-08-01] 16 → 22. 6m를 더 올려 잔디를 화면 아래로 내리고, 그 위에 생긴 어두운
 * 띠(원경 스탠드~밤하늘)를 타이틀 자리로 쓴다.
 * [2026-08-01 명암 배분] 22 → 23.5. 반경을 126m로 물린 뒤 잔디 상단 경계를 60%에
 * 맞추는 마지막 한 걸음이다. 25를 넘기면 골대 뒤 근경 스탠드의 검은 지붕이 프레임
 * 하단을 먹고, 먼 조명탑 halo가 제목 1행 높이로 더 내려와 실측 대비가 떨어진다.
 */
export const LOOK_AT_Y = 23.5


/** 랜딩 카메라 파라미터 묶음 — 계측 하네스(tools/tone-stats/harness.ts)와 테스트가 참조한다. */
export const LANDING_CAMERA = {
  fov: FOV,
  lookAt: { x: 0, y: LOOK_AT_Y, z: 0 },
  arcCenter: ARC_CENTER,
  arcAmp: ARC_AMP,
  arcOmega: ARC_OMEGA,
  /** t=0(정지 컷)의 기준 반경·높이. 구도 계약을 테스트가 수치로 못박는다. */
  radius: ORBIT_R,
  height: ORBIT_Y,
} as const

/**
 * 경과 시간 t(초)에서의 카메라 월드 좌표. three에 의존하지 않는 **순수 함수**라
 * 회귀 테스트가 궤적 전체를 샘플링해 "마스트를 관통하지 않는다"를 검증할 수 있다.
 * t=0은 호의 중심 = 정지 컷(prefers-reduced-motion에서 그리는 단 한 프레임)이다.
 */
export function landingCameraAt(t: number): { x: number; y: number; z: number } {
  const a = ARC_CENTER + ARC_AMP * Math.sin(t * ARC_OMEGA)
  const r = ORBIT_R + DOLLY_AMP * Math.sin(t * DOLLY_OMEGA)
  return {
    x: Math.cos(a) * r,
    y: ORBIT_Y + BOB_AMP * Math.sin(t * BOB_OMEGA),
    z: Math.sin(a) * r,
  }
}
