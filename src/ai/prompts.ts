// src/ai/prompts.ts
// 프로바이더 중립 프롬프트 빌더 (순수 함수).
// api/narrate.ts(서버)와 향후 호출부가 공유한다. DOM/네트워크 의존 없음 —
// Vercel Node 런타임에서도 그대로 import 가능하도록 순수하게 유지한다.

export type NarrateTask = 'pressq' | 'headline' | 'epilogue'

/**
 * 시스템 프롬프트 — 세이프가드 제약(설계 §7.1의 1단).
 * 실존 인물·팀 비판 금지, 상대 벤치 익명 지칭(§7.1(a)), 허위 인용 금지,
 * 사실·중립 질문만, 한국어, 대체역사 픽션 인지.
 */
export function buildSystemPrompt(): string {
  return [
    // 게임명은 밈 톤 제목 그대로 넣는다 — 프롬프트는 길이 제약이 없고,
    // 모델이 작품 세계관(대체역사·1인칭 감독물)을 잡는 데 오히려 도움이 된다.
    '당신은 축구 매니지먼트 게임 "현실에서 축덕인 내가, 이세계에선 국대 감독?"의 내레이터입니다.',
    '반드시 아래 제약을 지키세요:',
    '- 실존 인물·팀에 대한 비판·조롱·부정 평가를 하지 않는다.',
    '- 상대 팀 감독·코치진은 실명이나 실존 인물 페르소나로 지칭하지 말고 익명 직함(\'상대 벤치\')으로만 언급한다.',
    '- 그들이 실제로 하지 않은 발언을 인용하지 않는다.',
    '- 사실 서술과 중립적 질문만 사용한다.',
    '- 반드시 한국어로만 답한다.',
    '- 이 게임은 대체역사 픽션임을 인지하고, 픽션 세계관 안에서 서술한다.',
    '- 출력은 군더더기 없이 요청된 결과물만 낸다.',
  ].join('\n')
}

/**
 * 사실 왜곡 금지 조항 — 세 task가 공유한다.
 *
 * 왜 필요했나(2026-08-02, 실플레이 결함): 2-5 **패배** 경기의 헤드라인이
 * "대한민국, 멕시코에 2-0에서 5-2로 대승"으로 나왔다. 맥락에 담긴 것이 `score: [2,5]`뿐이라
 * 모델이 배열 순서를 자기 편한 대로 읽었고, 없던 경기 전개까지 지어냈다.
 * 호출부는 이제 승패를 한국어 낱말로 못 박아 넘긴다(pressconf.describeMatch). 아래 조항은
 * 그 값을 **재해석하지 말라**고 명시하는 두 번째 층이다.
 */
const FACT_RULES = [
  '※ 사실 제약(가장 중요 — 어기면 결과물은 폐기됩니다):',
  '- 맥락에 적힌 스코어와 승패를 절대 바꾸지 마세요. 진 경기를 이긴 것처럼, 이긴 경기를 진 것처럼 쓰면 안 됩니다.',
  '- 승패는 이미 판정되어 있습니다. "정규시간_결과"·"최종_결과"·"한줄_사실" 필드가 유일한 정답이며, 득점 숫자를 보고 다시 판정하지 마세요.',
  '- 득점은 "우리_팀_득점"·"상대_팀_득점"에 적힌 값 그대로만 씁니다. 스코어를 표기할 때는 "최종_스코어" 문자열을 그대로 사용하세요.',
  '- 맥락에 없는 경기 전개를 지어내지 마세요: 중간 스코어, 역전·재역전, 득점 시간대, 득점자, 퇴장, 부상 등 주어지지 않은 사실은 언급 금지입니다.',
  '- 패배·무승부를 승리의 어휘(대승·완파·제압 등)로 포장하지 마세요.',
].join('\n')

/**
 * task별 유저 프롬프트. context(사실 카드·답변 톤 등)를 그대로 주입한다.
 * 결정론(순수): 같은 입력이면 같은 문자열.
 */
export function buildUserPrompt(task: NarrateTask, context: Record<string, unknown>): string {
  // 들여쓴 JSON으로 준다 — 한 줄 JSON보다 필드 경계가 뚜렷해 모델이 라벨과 값을 덜 헷갈린다.
  const ctx = JSON.stringify(context, null, 2)
  switch (task) {
    case 'pressq':
      return [
        '다음 경기의 맥락(결정 로그·스코어 등)을 바탕으로,',
        '경기 직후 기자회견에서 감독에게 던질 기자 질문 1개를 한국어로 생성하세요.',
        '중립적이고 사실에 근거한 질문이어야 합니다.',
        '이긴 경기를 추궁하거나 진 경기를 축하하는 전제를 깔지 마세요.',
        FACT_RULES,
        `경기 맥락: ${ctx}`,
      ].join('\n')
    case 'headline':
      return [
        '다음 기자회견 답변의 톤과 경기 결과를 반영하여,',
        '스포츠 신문 1면 헤드라인 1개를 한국어로 작성하세요.',
        '자극적 비하 없이 사실을 담되 신문 헤드라인다운 함축을 사용하세요.',
        '헤드라인의 주어는 우리 팀이며, 승패 서술은 맥락의 "최종_결과"와 반드시 일치해야 합니다.',
        FACT_RULES,
        `맥락(결과·답변 톤): ${ctx}`,
      ].join('\n')
    case 'epilogue':
      return [
        '다음 캠페인 여정을 3~5문장의 한국어로 요약하세요.',
        '감독과 팀이 걸어온 길을 담담하고 사실적으로 서술합니다.',
        '전적과 도달 단계는 맥락에 적힌 값 그대로 쓰고, 우승하지 않았다면 우승했다고 쓰지 마세요.',
        FACT_RULES,
        `여정: ${ctx}`,
      ].join('\n')
  }
}
